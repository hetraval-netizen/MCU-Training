static void oled_write_packet(uint8_t control_type, uint8_t payload) {
    // Wait until the I2C bus is free
    while (I2C1->ISR & I2C_ISR_BUSY);
  
    // Configure for 2 bytes, Auto-End, and generate START
    I2C1->CR2 = 0;
    I2C1->CR2 |= (0x3C << 1) | (2 << I2C_CR2_NBYTES_Pos) | I2C_CR2_AUTOEND | I2C_CR2_START;
  
    // Send Byte 1: The Control Byte
    while (!(I2C1->ISR & I2C_ISR_TXIS)) {
      if (I2C1->ISR & I2C_ISR_NACKF) {
        GPIOA->ODR |= (1 << 5);      // Turn ON the Green LED to flag an error!
        I2C1->ICR |= I2C_ICR_NACKCF; 
        return;                      
      }
    }
    I2C1->TXDR = control_type;
  
    // Send Byte 2: The payload
    while (!(I2C1->ISR & I2C_ISR_TXIS)) {
      if (I2C1->ISR & I2C_ISR_NACKF) {
        GPIOA->ODR |= (1 << 5);      // Turn ON the Green LED to flag an error!
        I2C1->ICR |= I2C_ICR_NACKCF; 
        return;                      
      }
    }
    I2C1->TXDR = payload;
    
    // Wait for AUTOEND to finish and clear the flag
    while (!(I2C1->ISR & I2C_ISR_STOPF));
    I2C1->ICR |= I2C_ICR_STOPCF;
}
  
void oled_send_cmd(uint8_t cmd) { 
    oled_write_packet(0x00, cmd); 
}

void oled_send_data(uint8_t data) { 
    oled_write_packet(0x40, data); // 0x40 tells the OLED "this is a pixel, not a command!"
}

void oled_clear(void) {
    for (uint8_t page = 0; page < 8; page++) {
        oled_send_cmd(0xB0 + page); // Set Page (0-7)
        oled_send_cmd(0x00);        // Set Lower Column
        oled_send_cmd(0x10);        // Set Higher Column
        
        for (uint8_t col = 0; col < 128; col++) {
            oled_send_data(0x00);   // Write 0s to clear all 128 columns
        }
    }
}

void oled_draw_char(char c, uint8_t page, uint8_t column, bool invert) {
    if (c < 32 || c > 126) {
        c = ' ';
    }

    uint32_t font_index = c - 32;

    oled_send_cmd (0xB0 + page);
    oled_send_cmd (0x00 + (column & 0x0F));
    oled_send_cmd (0x10 + ((column >> 4) & 0x0F));

    for (int i = 0; i < 6; i++){
        uint8_t font = font_6x8[font_index][i];

        if (invert)
            font = ~font;

        oled_send_data(font);
    }

    oled_send_data(0x00);
}

void oled_print_str(char *str, uint8_t page) {
    int current_column = 0;
    uart_sendstring (str);
    uart_sendchar('\n');
    uart_sendchar('\r');
    while (*str != '\0'){

        oled_draw_char(*str, page, current_column, false);
        uart_sendchar(*str);
        uart_sendchar('\n');
        uart_sendchar('\r');
        current_column += 6;

        if (current_column > 124){
            break;
        }

        str++;
    }
}

void oled_print_str_highlight(char *str, uint8_t page) {
    int current_column = 0;
    uart_sendstring (str);
    uart_sendchar('\n');
    uart_sendchar('\r');
    while (*str != '\0'){

        oled_draw_char(*str, page, current_column, true);
        uart_sendchar(*str);
        uart_sendchar('\n');
        uart_sendchar('\r');
        current_column += 6;

        if (current_column > 124){
            break;
        }

        str++;
    }
}

void print_setting_oled(int led_pattern) {
    oled_clear();

    for (int i = 0; i < (MAX_PATTERNS); i++){
        if (led_pattern == i)
            oled_print_str_highlight(led_setting[i], i);
        else
            oled_print_str(led_setting[i], i);
    }
}